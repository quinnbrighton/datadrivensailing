#!/usr/bin/env python3
"""
Shared rule for deciding whether a regatta is a women's event.

Three consumers need this answer and used to each load data/women_regattas.csv on
their own: tag_womens.py (writes is_womens into the database), preprocess.py (the
is_women flag on every race the rating model trains on) and fantasy_server.py (the
w_flag feature and the women's-first weekend ordering).  Loading the same CSV three
times is fine; disagreeing about what it means is not, so the rule lives here.

Why a rule and not just the CSV:

  data/women_regattas.csv is generated by analysis/identify_womens_regattas.py, which
  scores each regatta by the average log-odds that its sailors' first names are female
  and keeps those over a threshold with more than ten sailors.  That misses two classes
  of event entirely:

    * Singlehanded championships.  Small fields fall under the sailor floor, so about a
      hundred regattas with "Women's" plainly in the title were never listed.
    * Annual events whose title carries the year.  "Toni Deutsch '58 Trophy 2025" is in
      the CSV; the 2026 edition is a different string, so it silently went untagged the
      moment the new season loaded — and would again every September.

So the CSV stays the primary source (it catches women's regattas whose names give no
hint, which no rule can), and these two rules are layered on top of it.
"""

import csv
import os
import re

# "wom[ae]n" covers women / woman / womens / women's / women’s (curly apostrophe) in
# any case.  Matching the bare stem rather than a full token is deliberate: the real
# data contains "Womens", "Women’s", "Women" and "(woman)" as separate spellings.
_WOMEN_RE = re.compile(r"wom[ae]n", re.I)

# A trailing year, so "Toni Deutsch '58 Trophy 2026" can be compared against the 2025
# edition already in the CSV.  Only a four-digit year at the very end is removed, which
# leaves "'58" and names like "SAISA Womens South #2" alone.
_YEAR_RE = re.compile(r"\s*(?:19|20)\d{2}\s*$")


def strip_year(name: str) -> str:
    """'Toni Deutsch '58 Trophy 2026' -> "toni deutsch '58 trophy" (lowercased)."""
    return _YEAR_RE.sub('', name).strip().lower()


def load_women_regatta_names(csv_path: str) -> set:
    """Read the generated women's-regatta list.  Missing file -> empty set."""
    names = set()
    if not os.path.exists(csv_path):
        return names
    with open(csv_path, newline='', encoding='utf-8') as f:
        for row in csv.DictReader(f):
            n = (row.get('regatta_name') or '').strip()
            if n:
                names.add(n)
    return names


def build_index(csv_names):
    """Pre-compute the year-stripped lookup once, for callers testing many names."""
    return {strip_year(n) for n in csv_names}


def is_womens_regatta(name: str, csv_names, stripped_index=None) -> bool:
    """True if this regatta name is a women's event.

    name           : the regatta name as stored
    csv_names      : set from load_women_regatta_names()
    stripped_index : optional build_index(csv_names), to avoid rebuilding per call

    Note "Women's" contains "men's", so nothing here may test for men by substring.
    A combined "Men's and Women's" event would match this rule; a scan of all 2,420
    distinct regatta names in the database found no such name, and the 50 men-only
    names are correctly excluded because none of them contains the women stem.
    """
    if not name:
        return False
    if name in csv_names:
        return True
    if _WOMEN_RE.search(name):
        return True
    if stripped_index is None:
        stripped_index = build_index(csv_names)
    return strip_year(name) in stripped_index


def womens_reason(name: str, csv_names, stripped_index=None) -> str:
    """Which rule matched — for logging and for auditing a retag."""
    if not name:
        return ''
    if name in csv_names:
        return 'csv-exact'
    if _WOMEN_RE.search(name):
        return 'name-rule'
    if stripped_index is None:
        stripped_index = build_index(csv_names)
    if strip_year(name) in stripped_index:
        return 'year-stripped'
    return ''
